#!/usr/bin/env python3
"""
Removal History — remember what was deliberately deleted, so it cannot come back.

Every manual review pass exports a shell script of files to remove. Those files
were examined and rejected by a human: blurry, redundant, uninteresting. Nothing
in the import pipeline knew about that decision, so re-importing an older source
tree would happily restore them and they would have to be rejected all over again.

This module reads those exported scripts and answers one question: has a file with
this name already been deliberately removed?

Matching is by NAME, not location, because the organizing scripts move files
freely — the location a file was deleted from tells you nothing about where an
incoming copy would land. Names are normalized so that the same photograph matches
across the suffixes the pipeline adds:

    DSCN1234_S3500_Clif_2.JPG  ->  dscn1234
    IMG_20210510_120254_Nicole.jpg  ->  img_20210510_120254

`-edited` is deliberately preserved: an edited variant is a different asset from
its original, and removing one says nothing about the other.

Usage:
    from removal_history import RemovalHistory

    history = RemovalHistory.from_directory(Path('Organized_Photos'))

    if history.was_removed('DSCN1234.JPG'):
        # Do not import; it was rejected during review

Standalone report:
    python3 removal_history.py                     # summarize the known history
    python3 removal_history.py --check FILENAME     # test one name
"""

import argparse
import re
import sys
from pathlib import Path

# Default location for exported removal scripts. They are generated by the HTML
# review pages and kept alongside the archive they describe.
DEFAULT_SCRIPT_DIR = Path(__file__).parent / "Organized_Photos"
SCRIPT_GLOB = "*remove*.sh"

# `rm "path"` (scripts generated before the shell-escaping fix) and `rm 'path'`
# (generated after it, where embedded single quotes appear as '\'').
_DOUBLE_QUOTED = re.compile(r"""^\s*rm\s+"(?P<path>.*)"\s*$""")
_SINGLE_QUOTED = re.compile(r"""^\s*rm\s+'(?P<path>.*)'\s*$""")

# Suffixes the pipeline appends. These are deliberately narrow, because
# over-stripping is dangerous in a way under-stripping is not: a name reduced too
# far collides with unrelated files and blocks legitimate imports, whereas a name
# left too long merely fails to match and the file gets imported for review again.
#
# The collision counter is capped at two digits. An earlier version used `_\d+$`,
# which chewed through the timestamp in IMG_20240101_120000_Nicole and reduced it
# to "img" — every date-stamped file would have collapsed onto one key and the
# whole import would have been blocked.
_COLLISION_COUNTER = re.compile(r'_\d{1,2}$')

# Owner suffix: _Clif, _Nicole
_PERSON_SUFFIX = re.compile(r'_[A-Z][a-z]+$')

# Camera model suffix: _S3500, _D3000, _OC5. Must begin with a letter so that a
# purely numeric trailing group (a time, a sequence) is never mistaken for one.
_MODEL_SUFFIX = re.compile(r'_[A-Z][A-Z0-9]{1,}$')

# The pipeline appends at most model, then person, then a collision counter, so
# three passes is the most that can legitimately come off.
_MAX_STRIP_PASSES = 3


# A YYYYMMDD_HHMMSS group. Its presence is what makes a pipeline-generated name
# uniquely identifying, so no strip is allowed to remove it.
_DATETIME_PATTERN = re.compile(r'\d{8}_\d{6}')


def _has_datetime(stem):
    """Report whether a stem still carries a YYYYMMDD_HHMMSS group."""
    return _DATETIME_PATTERN.search(stem) is not None


def normalize_media_name(filename):
    """
    Reduce a filename to a comparison key that survives pipeline renaming.

    The organizing scripts append a camera model suffix, an owner suffix, and a
    numeric counter on collision. A source file arriving fresh from a card or an
    export carries none of those, so a naive comparison would never match. This
    strips them, repeatedly, since several can be stacked.

    `-edited` markers are preserved on purpose — an edited variant is a separate
    asset, and deleting one implies nothing about the other.

    Args:
        filename: Bare filename, with or without extension

    Returns:
        str: Lowercased normalized stem, suitable as a dict key
    """
    stem = Path(filename).stem

    # Bounded rather than looping to exhaustion: the pipeline stacks at most three
    # suffixes, and an unbounded loop is what previously ate timestamps.
    for _ in range(_MAX_STRIP_PASSES):
        for pattern in (_COLLISION_COUNTER, _PERSON_SUFFIX, _MODEL_SUFFIX):
            stripped = pattern.sub('', stem)

            # Refuse a strip that would leave nothing, or that would remove the
            # datetime portion of a pipeline-generated name. Losing the timestamp
            # is what collapses unrelated files onto one key.
            if stripped == stem or not stripped:
                continue

            if _has_datetime(stem) and not _has_datetime(stripped):
                continue

            stem = stripped
            break
        else:
            break

    return stem.lower()


def parse_removal_script(script_path):
    """
    Extract the removed file paths from one exported removal script.

    Handles both quoting styles the exporters have produced. Lines that are not
    `rm` commands (shebang, comments, counters) are ignored.

    Args:
        script_path: Path to a generated removal script

    Returns:
        list of str: the paths named by `rm` lines, in file order
    """
    paths = []

    try:
        lines = Path(script_path).read_text(errors='replace').splitlines()
    except OSError:
        return paths

    for line in lines:
        for pattern in (_DOUBLE_QUOTED, _SINGLE_QUOTED):
            match = pattern.match(line)

            if match is None:
                continue

            path = match.group('path')

            # Undo the '\'' idiom used by single-quoted exports
            if pattern is _SINGLE_QUOTED:
                path = path.replace("'\\''", "'")

            paths.append(path)
            break

    return paths


class RemovalHistory:
    """
    The set of media names a human has deliberately removed.

    Attributes:
        names:   set of normalized names that were removed
        sources: dict of {script_name: count} for reporting
    """

    def __init__(self, names=None, sources=None):
        self.names = names or set()
        self.sources = sources or {}

    @classmethod
    def from_directory(cls, directory=None, glob=SCRIPT_GLOB):
        """
        Build a history from every removal script in a directory.

        Args:
            directory: Where the exported scripts live (default Organized_Photos/)
            glob:      Filename pattern identifying removal scripts

        Returns:
            RemovalHistory
        """
        if directory is None:
            directory = DEFAULT_SCRIPT_DIR

        directory = Path(directory)
        names = set()
        sources = {}

        if not directory.is_dir():
            return cls(names, sources)

        for script_path in sorted(directory.glob(glob)):
            paths = parse_removal_script(script_path)
            sources[script_path.name] = len(paths)

            for path in paths:
                names.add(normalize_media_name(Path(path).name))

        return cls(names, sources)

    def was_removed(self, filename):
        """
        Report whether a file with this name was deliberately removed.

        Args:
            filename: Bare filename or full path

        Returns:
            bool
        """
        if not self.names:
            return False

        return normalize_media_name(Path(filename).name) in self.names

    def __len__(self):
        return len(self.names)

    def describe(self):
        """Return a human-readable summary of what was loaded."""
        if not self.sources:
            return "No removal scripts found."

        lines = [f"Removal history: {len(self.names):,} unique names"]

        for name, count in self.sources.items():
            lines.append(f"  {count:6,} entries  {name}")

        total = sum(self.sources.values())
        collapsed = total - len(self.names)

        if collapsed > 0:
            lines.append(f"  ({collapsed:,} collapsed as duplicates across scripts "
                         f"or after suffix normalization)")

        return '\n'.join(lines)


def main():
    """Report the loaded history, or test specific filenames against it."""
    parser = argparse.ArgumentParser(
        description="Inspect the deliberate-removal history used to block re-imports"
    )
    parser.add_argument(
        '--script-dir',
        default=None,
        help=f"Directory holding removal scripts (default: {DEFAULT_SCRIPT_DIR})"
    )
    parser.add_argument(
        '--check',
        nargs='+',
        metavar='FILENAME',
        help="Report whether each filename was previously removed"
    )
    parser.add_argument(
        '--list',
        type=int,
        metavar='N',
        help="Print N normalized names, for eyeballing the normalization"
    )

    args = parser.parse_args()
    history = RemovalHistory.from_directory(args.script_dir)

    print(history.describe())

    if args.list:
        print(f"\nFirst {args.list} normalized names:")
        for name in sorted(history.names)[:args.list]:
            print(f"  {name}")

    if args.check:
        print()
        for filename in args.check:
            verdict = 'REMOVED (would be blocked)' if history.was_removed(filename) else 'not in history'
            print(f"  {filename:52s} -> {verdict}")
            print(f"    normalizes to: {normalize_media_name(filename)}")

    if not history.names:
        sys.exit(1)


if __name__ == '__main__':
    main()
